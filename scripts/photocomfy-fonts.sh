#!/bin/sh
# Materialises the PhotoComfy Chinese font pack: the fonts that iOS and Android builds embed for
# the Type tool (docs/photocomfy-fonts.md). The fonts stay out of git (agent.md §13); this script
# downloads each file named in scripts/photocomfy-fonts.lock, checks it against the SHA-256 there,
# and writes the manifest crates/text/build.rs reads (PHOTOCOMFY_FONTS_DIR).
#
#   scripts/photocomfy-fonts.sh [--check] [PACK_DIR]      # default: photocomfy-fonts/ at the repo root
#
# --check downloads nothing: it only reports a missing or changed file (non-zero exit).
#
# Each lock line's download URLs are tried in order. GitHub API URLs return the file itself when
# asked for the raw media type, which works where raw.githubusercontent.com is unreachable;
# GH_TOKEN / GITHUB_TOKEN, when set, lift the API's anonymous rate limit for them.

set -eu

REPO="$(cd "$(dirname "$0")/.." && pwd)"
LOCK="$REPO/scripts/photocomfy-fonts.lock"
TAB="$(printf '\t')"

CHECK=false
if [ "${1:-}" = "--check" ]; then
    CHECK=true
    shift
fi
PACK="${1:-$REPO/photocomfy-fonts}"

sha256() {
    if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi
}

# download <url> <file>: curl's own retries cover a dropped connection.
download() {
    dl_url="$1"
    dl_file="$2"
    set -- -fsSL --connect-timeout 20 --max-time 1200 --retry 3 --retry-delay 5
    case "$dl_url" in
        https://api.github.com/*)
            set -- "$@" -H "Accept: application/vnd.github.raw"
            if [ -n "${GH_TOKEN:-}" ]; then
                set -- "$@" -H "Authorization: Bearer $GH_TOKEN"
            elif [ -n "${GITHUB_TOKEN:-}" ]; then
                set -- "$@" -H "Authorization: Bearer $GITHUB_TOKEN"
            fi
            ;;
    esac
    curl "$@" -o "$dl_file" "$dl_url" 2>/dev/null
}

# fetch <relative path> <sha256> <urls>
fetch() {
    rel="$1"
    want="$2"
    dest="$PACK/$rel"
    if [ -f "$dest" ] && [ "$(sha256 "$dest")" = "$want" ]; then
        return 0
    fi
    if $CHECK; then
        echo "photocomfy-fonts: missing or changed: $rel" >&2
        return 1
    fi
    mkdir -p "$(dirname "$dest")"
    set -f
    old_ifs="$IFS"
    IFS=';'
    set -- $3
    IFS="$old_ifs"
    set +f
    for candidate in "$@"; do
        url="$(printf '%s' "$candidate" | sed -e 's/^ *//' -e 's/ *$//')"
        [ -n "$url" ] || continue
        member=""
        case "$url" in
            *.zip#*) member="${url#*#}"; url="${url%%#*}" ;;
        esac
        echo "fetching $rel <- $url" >&2
        rm -f "$dest"
        out="$dest.part"
        if download "$url" "$out"; then
            if [ -n "$member" ]; then
                unzip -p "$dest.part" "$member" > "$dest" 2>/dev/null || rm -f "$dest"
                rm -f "$dest.part"
            else
                mv "$dest.part" "$dest"
            fi
        fi
        if [ -f "$dest" ]; then
            got="$(sha256 "$dest")"
            if [ "$got" = "$want" ]; then
                return 0
            fi
            echo "photocomfy-fonts: $url gave $got; the lock wants $want" >&2
        fi
    done
    rm -f "$dest" "$dest.part"
    echo "photocomfy-fonts: could not fetch $rel from any of its sources" >&2
    return 1
}

[ -f "$LOCK" ] || { echo "photocomfy-fonts: no lock file at $LOCK" >&2; exit 1; }

missing=false
manifest=''
attribution=''
line_no=0
while IFS= read -r line || [ -n "$line" ]; do
    line_no=$((line_no + 1))
    case "$line" in
        '' | '#'*) continue ;;
    esac
    fields="$(printf '%s\n' "$line" | awk -F' [|] ' -v OFS="$TAB" '{ $1 = $1; print }')"
    set -f
    IFS="$TAB"
    # shellcheck disable=SC2086
    set -- $fields
    IFS=' '
    set +f
    case "$1" in
        font)
            [ "$#" -eq 10 ] || { echo "$LOCK:$line_no: a font line has 10 fields, found $#" >&2; exit 1; }
            fetch "$4" "$8" "${10}" || missing=true
            manifest="$manifest$2 | $3 | $4 | $5 | $6 | $7 | $8 | $9
"
            attribution="$attribution| \`$4\` | $2 $3 | $6 | \`$7\` | $9 |
"
            ;;
        text)
            [ "$#" -eq 4 ] || { echo "$LOCK:$line_no: a text line has 4 fields, found $#" >&2; exit 1; }
            fetch "$2" "$3" "$4" || missing=true
            ;;
        *)
            echo "$LOCK:$line_no: unknown line type '$1'" >&2
            exit 1
            ;;
    esac
done < "$LOCK"

if $missing; then
    exit 1
fi
if $CHECK; then
    exit 0
fi

mkdir -p "$PACK/fonts"
{
    echo "# PhotoComfy Chinese font pack: generated by scripts/photocomfy-fonts.sh from scripts/photocomfy-fonts.lock."
    echo "# family | style | file | scripts | licence | licence file | sha256 | source"
    printf '%s' "$manifest"
} > "$PACK/fonts/manifest.txt"
{
    echo "# PhotoComfy Chinese font pack"
    echo
    echo "Generated by \`scripts/photocomfy-fonts.sh\` from \`scripts/photocomfy-fonts.lock\`: the files are byte-identical"
    echo "to their sources, each checked against the SHA-256 in the lock. iOS and Android builds embed them for the Type tool."
    echo
    echo "| File | Family / style | Licence | Licence file | Source |"
    echo "|---|---|---|---|---|"
    printf '%s' "$attribution"
} > "$PACK/ATTRIBUTION.md"
echo "photocomfy-fonts: ready in $PACK"
